package ru.zaroslikov.incubator.domain.model

/**
 * План на один день инкубации: какими должны быть температура, влажность,
 * перевороты и проветривания.
 *
 * Все четыре величины — числа, и все четыре nullable. `null` значит «нормы нет»:
 * либо пользователь очистил поле, либо этим занимается сама автоматика инкубатора
 * (см. [setAutoIncubator][ru.zaroslikov.incubator.domain.incubation.setAutoIncubator],
 * которая как раз проставляет `null`). Ноль — не то же самое: он значит «не делать»,
 * и это тоже норма, которую видно в счётчиках дня.
 *
 * [over] — сколько раз за день переворачивать. Режимы по умолчанию писали это
 * диапазоном («2-3», «4-6»); в число уехала верхняя граница.
 *
 * Проветривание с девятой версии схемы разделено надвое: [airingCount] — сколько раз
 * за день, [airingTime] — сколько минут длится одно проветривание. Одной строкой
 * («2 раза по 5 минут») это не считалось: из неё нельзя было взять ни норму по разам,
 * ни минуты, не разбирая текст.
 */
data class Value(
    var id: Long = 0,
    val day: Int,
    var temp: Double?,
    var damp: Double?,
    var over: Int?,
    var airingCount: Int?,
    var airingTime: Int?,
    var note: String,
    var idPT: Long
)
