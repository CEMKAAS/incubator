package ru.zaroslikov.incubator.domain.model

/**
 * Закладка — партия яиц, заложенная в инкубатор. Раньше эта сущность называлась
 * IncubatorTable и хранилась в таблице `Incubator`, что путало её с самим устройством.
 *
 * [airing] и [over] — что фактически использовали при генерации расписания этой закладки;
 * у самого устройства ([Incubator.autoAiring], [Incubator.autoTurn]) это возможность.
 * Значения уже запечены в строки [Value], переписывать их задним числом нельзя.
 *
 * [price] и [pricePerEgg] хранят ровно то, что ввёл пользователь: цену за яйцо либо
 * за всю партию. Пересчитывать одно в другое при сохранении нельзя — количество яиц
 * ещё изменится, и намерение «22 ₽ за яйцо» тогда потеряется.
 *
 * [endReason], [chickPrice] и [chickPricePerHead] появляются только при завершении.
 * Пустая [endReason] у завершённой закладки означает «завершили в срок»: причину
 * спрашивают лишь при досрочном завершении, когда птенцов уже не будет и вся закладка
 * уходит в расход. [chickPrice] с [chickPricePerHead] — та же пара, что [price] с
 * [pricePerEgg], и хранятся так же дословно: цена за одного птенца либо за всех.
 *
 * [time] — час закладки, пара к [data]. Дата решает, какой сейчас день инкубации, и
 * границ дня время не двигает: день считается целыми сутками от [data], иначе поехало
 * бы всё расписание. Считается по нему ровно одно — момент, с которого экран инкубатора
 * предлагает внести итог («срок вышел» наступает в час закладки того дня, а не в
 * полночь): `FinishedBatchPrompt.batchFinishMoment` в `:app`. Пустая строка у закладок,
 * созданных до появления поля, значит «не спрашивали», а не «полночь», и тогда днём
 * вывода считаются целые сутки.
 *
 * [breed] — порода внутри вида, одна на закладку; пусто — не указывали. **В одной
 * закладке одна порода**, и это правило, а не ограничение поля: яйца разных пород
 * закладывают разными закладками, даже если они лежат в одном лотке под одним режимом.
 * Форма закладки умеет заложить несколько пород разом — но сохраняет их отдельными
 * закладками, по одной на породу, каждую со своими яйцами и своей ценой. Так у каждой
 * породы свой вывод, своя отбраковка и свои деньги без второго учёта внутри закладки:
 * всё, что считает яйца и рубли, читает закладку и ни о каком разборе по породам не
 * знает. Между пятнадцатой и семнадцатой версиями схемы породы лежали строками
 * отдельной таблицы, по нескольку на закладку, и каждое число закладки приходилось
 * держать в двух местах — восемнадцатая вернула одно поле.
 *
 * [eggRejected] — отбраковка, записанная руками в форме закладки, помимо
 * овоскопирований (`Candling.rejected`). Одно другого не заменяет: овоскопирование —
 * событие со своим днём и датой, а это графа для яиц, убранных из инкубатора между
 * ними: треснувших, протухших, разбитых. «Осталось» вычитает из заложенного обе
 * величины сразу, поэтому вписывать сюда уже записанное овоскопированием нельзя.
 *
 * [hidden] — «убрана в архив» в терминах интерфейса: закладка пропадает из списка
 * инкубатора, но остаётся в базе и во всех подсчётах, потому что она правда была.
 * Не путать с [arhive]: та означает «инкубация окончена» и досталась в наследство от
 * первой версии схемы вместе с именем колонки `Archive`, которое поэтому и занято.
 * Прятать можно только законченную закладку — идущая нужна на виду.
 */
data class Batch(
    val id: Long = 0,
    val title: String, // название
    val type: String, // ведущий вид птицы, задаёт режим инкубации
    val data: String,  // Дата начала закладки
    val eggAll: Int, // заложено яиц
    val eggAllEND: Int, // выведено
    val airing: String, //не авто = 0, авто = 1
    val over: String,  //не авто = 0, авто = 1
    var arhive: String, //не архив =0, Архив = 1
    val dateEnd: String,
    val note: String,
    val incubatorId: Long = 0, // инкубатор, которому принадлежит закладка
    val price: Int = 0, // введённая стоимость в рублях, 0 — не указана
    val pricePerEgg: Boolean = true, // true — [price] за яйцо, false — за всю партию
    val endReason: String = "", // причина досрочного завершения; пусто — завершили в срок
    val chickPrice: Int = 0, // введённая стоимость птенцов в рублях, 0 — не указана
    val chickPricePerHead: Boolean = true, // true — [chickPrice] за птенца, false — за всех
    val hidden: Boolean = false, // убрана из списка инкубатора; в подсчётах участвует
    val time: String = "", // время закладки «ЧЧ:ММ»; пусто — не указано
    val eggRejected: Int = 0, // отбраковано яиц помимо овоскопирований
    /** Порода одной строкой; пусто — не указывали. Одна на закладку, см. выше. */
    val breed: String = "",
)

/**
 * Породы, которые уже вводили для птицы [type], — подсказки под полем «Порода» в форме
 * закладки, чтобы «Ломан Браун» не набирали заново на каждой закладке и не плодили
 * «ломан браун» рядом с «Ломан Браун», по которым статистика посчитала бы две породы.
 *
 * Только по своему виду: порода принадлежит птице, и куриная порода в подсказках под
 * уткой — шум. Последние закладки идут первыми — что закладывали недавно, то скорее
 * заложат снова, — а повторы сняты без учёта регистра и краёв, и остаётся написание из
 * самой свежей закладки: если породу однажды переименовали, предлагать надо новое имя.
 */
fun knownBreeds(batches: List<Batch>, type: String): List<String> =
    batches.asSequence()
        .filter { it.type == type }
        .sortedByDescending { it.id }
        .map { it.breed.trim() }
        .filter { it.isNotEmpty() }
        .distinctBy { it.lowercase() }
        .toList()

/**
 * Итог диалога завершения в срок: сколько вывелось и почём ушли птенцы.
 *
 * Отдельный тип, а не три параметра: диалог, ViewModel и `:domain` передают его друг
 * другу как одно целое, и цена не может отстать от вывода по дороге.
 */
data class HatchOutcome(
    val hatched: Int,
    val chickPrice: Int = 0,
    val chickPricePerHead: Boolean = true,
)

/**
 * Закладка, доведённая до срока: птенцы вывелись, закладка уходит в архив.
 *
 * Птенцов не может быть больше, чем яиц, и зажимается это здесь, а не только в поле
 * ввода: поле правит текст, а число сюда может прийти и из другого места.
 *
 * Причина завершения не пишется: пустая [Batch.endReason] у завершённой закладки и
 * означает «в срок». Пара к [stoppedEarly], и тоже одна на все места, откуда закладку
 * завершают: шторка закладки, меню карточки и подсказка «Инкубация завершена».
 */
fun Batch.finishedOnTime(outcome: HatchOutcome, dateEnd: String): Batch = copy(
    arhive = "1",
    dateEnd = dateEnd,
    endReason = "",
    eggAllEND = outcome.hatched.coerceIn(0, eggAll),
    chickPrice = outcome.chickPrice.coerceAtLeast(0),
    chickPricePerHead = outcome.chickPricePerHead,
)

/**
 * Закладка, возвращённая из архива обратно в инкубацию.
 *
 * Итог завершения стирается целиком — и птенцы с их ценой, и причина досрочного, и дата
 * окончания. Закладка снова идёт, а значит вывода у неё ещё не было: оставленный
 * [eggAllEND] попал бы в «выведено» инкубатора, который суммирует все закладки подряд,
 * и показал бы птенцов, которых пока нет. Завершат её заново — заново и спросят.
 *
 * Одна функция на оба места, откуда закладку возвращают в работу: меню её карточки и
 * экран архива. Разойдись они, «выведено» зависело бы от того, каким путём нажали.
 */
fun Batch.reopened(): Batch = copy(
    arhive = "0",
    dateEnd = "",
    eggAllEND = 0,
    endReason = "",
    chickPrice = 0,
    chickPricePerHead = true,
    // Спрятанной идущая закладка быть не может: за ней следят каждый день.
    hidden = false,
)

/**
 * Закладка, прерванная досрочно: птенцов не будет, вся партия уходит в расход.
 *
 * Ноль в [Batch.eggAllEND] здесь — итог, а не его отсутствие: «средний вывод» инкубатора
 * считает такую закладку наравне с остальными. Причина обязательна и непустая — именно
 * она отличает [BatchStatus.Stopped] от [BatchStatus.Hatched], и пустая строка означала
 * бы «довели до срока».
 *
 * Одна функция на оба места, откуда закладку прерывают: «Завершить досрочно» в её
 * собственном листе и архив всего инкубатора, который прерывает разом все идущие в нём
 * закладки. Разойдись они — итог зависел бы от того, каким путём нажали, ровно как это
 * могло случиться с [reopened].
 *
 * [dateEnd] — параметр, а не `Date()` внутри: при архиве инкубатора одним действием
 * прерывается несколько закладок, и дата окончания у них должна быть одна.
 *
 * [Batch.hidden] не трогается: «прервана» — про инкубацию, «убрана» — про список, и
 * решает второе не эта функция.
 */
fun Batch.stoppedEarly(reason: String, dateEnd: String): Batch = copy(
    arhive = "1",
    dateEnd = dateEnd,
    eggAllEND = 0,
    chickPrice = 0,
    chickPricePerHead = true,
    endReason = reason.trim(),
)
