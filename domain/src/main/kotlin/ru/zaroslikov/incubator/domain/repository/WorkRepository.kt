package ru.zaroslikov.incubator.domain.repository

/**
 * Напоминания — то, что живёт вне базы, в планировщике системы.
 *
 * **Метод здесь один, и это следствие того, как устроены напоминания.** Раньше их было
 * три — «поставить закладке», «снять у закладки», «снять все», — и каждый вызывающий
 * должен был помнить, какое действие соответствует тому, что он только что записал в
 * базу: завершил закладку — сними, вернул в работу — поставь, сохранил форму — сними и
 * поставь заново. Помнить это в шести местах значит однажды забыть, и забывали:
 * сохранение формы завершённой закладки воскрешало её будильники.
 *
 * Расписание же целиком выводится из базы — какие закладки идут и какие у них времена, —
 * поэтому единственное осмысленное действие после любой записи это «пересчитай». Кто
 * именно изменился, планировщику знать незачем: он всё равно перечитает всё.
 */
interface WorkRepository {

    /**
     * Расписание могло измениться — пересобрать его по базе.
     *
     * Вызывается после записи, а не вместо неё: считает по тому, что уже лежит в базе.
     * Возвращается сразу, работа идёт в фоне — вызывающему нечего ждать.
     */
    fun refreshReminders()
}
