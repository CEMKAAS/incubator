package ru.zaroslikov.incubator.domain.model

/**
 * Фактический замер в закладке — что термометр и гигрометр показали на самом деле.
 *
 * Не путать с [Value]: та хранит план на день инкубации (какими температура и влажность
 * должны быть), а замер — что было. Из разницы между ними и берётся отклонение
 * в шторке закладки.
 *
 * [idValue] — день расписания ([Value.id]), к которому относится замер. Именно строка,
 * а не календарная дата: дату начала закладки правят, дату на телефоне тоже, и замер,
 * привязанный к числу, после этого попал бы не в тот день инкубации.
 *
 * Числа здесь везде, и везде `null` значит «не записали»: [temp] и [damp] — показания,
 * [over] — сколько раз перевернули, [airingCount] — сколько раз проветрили,
 * [airingTime] — сколько минут длилось одно проветривание. Последние две колонки
 * появились в девятой версии схемы вместо одной строки `airing`, в которой лежали
 * то минуты, то «Авто», и которую приходилось разбирать регулярным выражением.
 *
 * [groupId] — метка замера, записанного **по инкубатору**, а не по закладке (схема v17).
 * Термометр один на прибор, а закладок в нём несколько, и показание, снятое с него,
 * относится к каждой идущей: такой замер ложится по одной копии в строку сегодняшнего
 * дня каждой из них, и все копии несут один и тот же [groupId]. Копии, а не отдельная
 * таблица, потому что всё, что читает замеры — шторка закладки, аналитика дня, итог,
 * среднее для экспорта расписания, — читает их при дне закладки и о приборе не знает;
 * метка нужна только шторке инкубатора, чтобы показать группу одной строкой и править
 * или удалять её целиком. `null` — замер внесли внутри закладки, он только её.
 */
data class Measurement(
    val id: Long = 0,
    val idValue: Long,
    val time: String,
    val temp: Double? = null,
    val damp: Double? = null,
    val over: Int? = null,
    val airingCount: Int? = null,
    val airingTime: Int? = null,
    val note: String = "",
    val groupId: String? = null,
) {
    /** Сколько всего минут проветривания записал этот замер: разы × длительность. */
    val airingTotalMinutes: Int
        get() = (airingCount ?: 0) * (airingTime ?: 0)
}
