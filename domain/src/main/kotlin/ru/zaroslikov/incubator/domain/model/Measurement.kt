package ru.zaroslikov.incubator.domain.model

/**
 * Фактический замер в закладке — что термометр и гигрометр показали на самом деле.
 *
 * Не путать с [Value]: та хранит план на день инкубации (какими температура и влажность
 * должны быть), а замер — что было. Из разницы между ними и берётся отклонение
 * в шторке закладки.
 *
 * [idValue] — день расписания ([Value.id]), к которому относится замер. Именно строка,
 * а не календарная дата: дату начала закладки правят, дату на телефоне тоже, и замер,
 * привязанный к числу, после этого попал бы не в тот день инкубации.
 *
 * [temp] и [damp] — числа; `null` значит «не записали». [over] и [airing] здесь
 * счётчики (сколько раз перевернули и проветрили) и остаются строками, как в [Value].
 */
data class Measurement(
    val id: Long = 0,
    val idValue: Long,
    val time: String,
    val temp: Double? = null,
    val damp: Double? = null,
    val over: String = "",
    val airing: String = "",
    val note: String = "",
)
