package ru.zaroslikov.incubator.domain.model

/**
 * Итог одного овоскопирования: сколько яиц на нём выбраковали.
 *
 * Отдельная запись на каждое овоскопирование, а не колонка в [Batch]: их за закладку
 * бывает два или три ([ru.zaroslikov.incubator.domain.incubation.setOvoskop]), и
 * «сколько убрали на первом» — не то же самое, что «сколько убрали всего». Из суммы
 * [rejected] по закладке и получается «осталось сейчас»; одна колонка эту сумму
 * сохранила бы, но потеряла бы её слагаемые.
 *
 * [day] — день инкубации, а не календарная дата, ровно по той же причине, по какой
 * к дню расписания привязан [Measurement]: дату начала закладки правят, часы на
 * телефоне переводят, а день инкубации от этого не меняется. Пара [idPT] + [day]
 * уникальна: овоскопирование в один день проводят один раз, повторное сохранение
 * переписывает прежний итог.
 *
 * [date] — когда это записали, «dd.MM.yyyy». Справочно, для истории: на счёт яиц
 * она не влияет.
 */
data class Candling(
    val id: Long = 0,
    val idPT: Long,
    val day: Int,
    val date: String,
    val rejected: Int,
)
