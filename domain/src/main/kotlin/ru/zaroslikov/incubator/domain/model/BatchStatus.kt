package ru.zaroslikov.incubator.domain.model

/**
 * В каком из трёх состояний закладка.
 *
 * Третьей колонки под это нет и не нужно: состояние целиком выводится из [Batch.arhive]
 * и [Batch.endReason], которые пишутся при завершении вместе, одной записью. Хранить его
 * отдельно значило бы завести поле, которое можно рассогласовать с этими двумя.
 *
 * [Stopped] отделён от [Hatched] потому, что это разные исходы, а не разные оттенки
 * одного: закладка, доведённая до срока, кончилась птенцами (пусть даже нулём — бывает и
 * так), а прерванная кончилась решением человека убрать её из инкубатора раньше времени.
 * Смотреть на них хочется порознь — «сколько раз вывелось» и «сколько раз сорвалось» это
 * два разных вопроса, и в общей куче «Завершённые» второй не задать.
 */
enum class BatchStatus {
    /** Идёт: [Batch.arhive] == "0". */
    Active,

    /** Дошла до конца срока. Птенцов могло вывестись и ноль — это тоже итог. */
    Hatched,

    /** Прервана досрочно: у неё есть [Batch.endReason], и только у неё. */
    Stopped,
}

/**
 * Статус закладки.
 *
 * Порядок проверок важен: непустая [Batch.endReason] у идущей закладки означала бы
 * причину завершения у незавершённой, чего [reopened] как раз и не допускает — но если
 * такая строка всё же попадётся (правка базы руками, недописанная миграция), закладка
 * должна читаться как идущая, а не как прерванная: `arhive` старше и главнее.
 */
val Batch.status: BatchStatus
    get() = when {
        arhive == "0" -> BatchStatus.Active
        endReason.isNotBlank() -> BatchStatus.Stopped
        else -> BatchStatus.Hatched
    }

/**
 * Закладку можно отдать файлом — другому телефону или себе про запас.
 *
 * Только удачно завершённая: доведена до срока ([BatchStatus.Hatched]) и птенцы из
 * неё были. Файл закладки — это её режим, предлагаемый как образец, и образцом может
 * быть только то, что сработало. Прерванная закладка образцом не бывает — её режим
 * не довели до конца; закладка с нулём птенцов — тоже, ноль там итог, а не пропуск,
 * и делиться нечем. Идущая закладка ещё ничего не доказала.
 *
 * Здесь, рядом со [status], а не в `:app`: «удачно» — это про закладку, а не про экран,
 * и меню карточки, шторка и всё, что появится потом, обязаны отвечать одинаково.
 */
val Batch.exportable: Boolean
    get() = status == BatchStatus.Hatched && eggAllEND > 0
