package ru.zaroslikov.incubator.domain.model

/**
 * Инкубатор — физическое устройство. Все закладки ([Batch]) создаются внутри него.
 *
 * [name] и [capacity] обязательны при создании, как и флаги автоматики.
 * [capacity] равна нулю только у инкубатора, синтезированного при миграции с первой
 * версии базы: там этих данных попросту не было, и интерфейс просит их заполнить.
 * [price] — рубли, ноль означает «не указана».
 *
 * [hidden] — «убран в архив»: устройство больше не в работе и его карточка не нужна
 * на главном экране. Как и у закладки, это решение о списке, а не о данных: закладки
 * убранного инкубатора продолжают идти, напоминать и считаться во всех показателях.
 * Своего «завершения», как `Batch.arhive`, у инкубатора нет — устройство не кончается,
 * — поэтому и второго флага здесь не заведено.
 */
data class Incubator(
    val id: Long = 0,
    val name: String,
    val capacity: Int,
    val brand: String = "",
    val model: String = "",
    val price: Int = 0,
    val note: String = "",
    val autoTurn: Boolean,
    val autoAiring: Boolean,
    val hidden: Boolean = false,
)
