package ru.zaroslikov.incubator.ui

import androidx.compose.runtime.staticCompositionLocalOf
import ru.zaroslikov.incubator.settings.Units

/**
 * Единицы измерения из «Настроек» — градусы и валюта — для всего, что рисует числа.
 *
 * Через `CompositionLocal`, а не параметром каждого экрана: температуру и деньги
 * показывают десятки мест — плашки дня, журнал замеров, аналитика, финансы, формы, — и
 * тянуть через них ещё одно значение значило бы переписать все сигнатуры ради строки,
 * которую каждое из них лишь подставляет после числа. `MainActivity` подписан на
 * `AppSettings.unitsFlow()` и подставляет его в корне, поэтому выбор в «Настройках»
 * перерисовывает приложение сразу, как и смена темы.
 *
 * `static`, потому что меняется оно раз в год: подписка каждого читателя на это значение
 * по отдельности стоила бы дороже одной полной перекомпозиции при смене.
 *
 * Только для показа. То, что ViewModel держит строками в полях ввода, переводится в
 * самой ViewModel по `AppSettings.temperatureUnit` — см. `ValueFormat`.
 */
val LocalUnits = staticCompositionLocalOf { Units.DEFAULT }
