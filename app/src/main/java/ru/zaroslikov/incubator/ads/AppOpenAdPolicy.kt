package ru.zaroslikov.incubator.ads

/**
 * Молчать ли рекламе при запуске в этот раз.
 *
 * Правило одно: **первый запуск и первый запуск после обновления проходят без неё.**
 * Человек, который только что поставил приложение, ещё не знает, что это; тот, кто
 * обновился, хочет увидеть, что изменилось. Реклама поверх обоих читалась бы как
 * «приложение — это реклама».
 *
 * «Первый запуск этой версии» узнаётся по коду версии, который видели в прошлый раз
 * ([seenVersion], `AppSettings.adsVersionCode`): `null` — установку ещё не запускали,
 * другое число — обновились. Не по `is_first_launch` из `MainActivity` и не по
 * `guidePending`: первый гаснет при первом же чтении, второй поднят лишь у тех, кто не
 * закрыл инструкцию, а обновление после этой версии инструкции уже не покажет.
 *
 * [guideShowing] — второй вход в то же правило: пока инструкция на экране, рекламы нет,
 * даже если процесс убили посреди неё и версия уже «видена». Инструкция — и есть тот
 * первый запуск, который договорились не перебивать.
 *
 * Чистая функция, чтобы `AppOpenAdPolicyTest` перебрал все четыре случая без Android.
 */
fun shouldMuteAppOpenAd(
    seenVersion: Int?,
    currentVersion: Int,
    guideShowing: Boolean,
): Boolean = guideShowing || seenVersion != currentVersion
