package ru.zaroslikov.incubator.rustore

import ru.zaroslikov.incubator.BuildConfig

/**
 * Собрана ли эта версия для RuStore — и, значит, показывать ли хоть что-нибудь из `rustore/`.
 *
 * Признак — буква «r» в конце `versionName`: «1.1.0r» уезжает в RuStore, «1.1.0» —
 * куда угодно ещё (APK с сайта, другой магазин, сборка для себя). Отдельного
 * `productFlavor` под это нет намеренно: варианты сборки размножают конфигурации,
 * ProGuard-правила и то, что нужно проверить руками перед выпуском, а вся разница
 * здесь — показывать или не показывать четыре вещи. Суффикс же виден и в самом
 * приложении, на экране «О приложении», то есть по установленной версии сразу понятно,
 * какая она.
 *
 * **Молчат все четыре двери в RuStore, а не только кнопки.** Предложить обновление
 * через магазин, которого у человека нет, — это отправить его туда, откуда он приложение
 * не брал; попросить оценку — то же самое; пуши едут через тот же SDK. Поэтому вместе с
 * карточкой «Оценить / Проверить обновление» отключаются автоматическая проверка
 * обновления с её карточкой внизу экрана, просьба оценить после вывода и инициализация
 * пуш-клиента. Само наличие RuStore на телефоне здесь ни при чём: SDK и так переживает
 * его отсутствие молча (см. `AppUpdateController`, `ReviewController`), но это ответ на
 * другой вопрос — «магазина нет на этом телефоне», а не «эта сборка не из магазина».
 *
 * Регистр не важен: «1.1.0R» — та же сборка, просто набранная иначе.
 */
val IS_RUSTORE_BUILD: Boolean
    get() = isRuStoreVersion(BuildConfig.VERSION_NAME)

/** Само правило, отдельно от `BuildConfig`, — чтобы его можно было проверить тестом. */
fun isRuStoreVersion(versionName: String): Boolean =
    versionName.trim().endsWith("r", ignoreCase = true)
