package ru.zaroslikov.incubator.work

import ru.zaroslikov.incubator.domain.model.Batch
import ru.zaroslikov.incubator.domain.model.Time
import java.util.Calendar
import java.util.TimeZone

/**
 * Вся арифметика напоминаний, без WorkManager и без Android.
 *
 * Отделено от [ReminderScheduler] нарочно: имя работы, номера уведомлений и время
 * ближайшего срабатывания — это правила, которые надо уметь проверить тестом, а не
 * привычка одной реализации. `ReminderPlanTest` пинает именно этот файл.
 *
 * Главное правило здесь одно: **напоминание принадлежит закладке, а не её названию**.
 * Раньше и метка работы, и её уникальное имя строились из названия закладки и времени
 * («08:00»), и оба ломались одинаково. Две закладки, поставленные на восемь утра,
 * делили одно уникальное имя — вторая молча вытесняла первую, а снятие уведомлений у
 * второй уносило работу, на которую рассчитывала первая. Переименование закладки
 * оставляло её прежние работы висеть под старой меткой, снять которую было уже нечем.
 * Идентификатор закладки не совпадает ни с чьим и не меняется, поэтому ключи считаются
 * от него.
 */

/**
 * Метка, которой помечена работа-напоминание приложения.
 *
 * Нужна пересборке ([ReminderSync]): найти поставленную работу можно и по уникальному
 * имени, но метка отвечает ещё на вопрос «а не осталось ли чего-нибудь лишнего», а
 * общий `cancelAllWork()` унёс бы и то, что появится завтра.
 */
const val REMINDER_TAG = "incubator-reminder"

/**
 * Уникальное имя единственной работы-напоминания.
 *
 * Работа одна на всё приложение, и это главная перемена. Прежде их было по одной на
 * каждую пару «закладка × время», и хозяйство с двумя десятками идущих закладок по
 * четыре напоминания упиралось в потолок планировщика — `Configuration.maxSchedulerLimit`
 * по умолчанию 50, а у самого JobScheduler на приложение 100 заданий; за порогом часть
 * работ просто не доезжала до системы, и напоминания переставали приходить без единой
 * ошибки. Одна работа знает лишь **ближайший момент**, показывает всё, что на него
 * пришлось, и ставит следующую — сколько бы закладок ни завели, работа остаётся одна.
 */
const val REMINDER_WORK_NAME = "incubator-reminders"

/**
 * Номер уведомления — свой у каждой пары «закладка + время».
 *
 * Раньше номер был константой, и одно уведомление затирало другое: из трёх закладок в
 * шторке оставалась видна одна, последняя. Считается как «номер закладки × число минут
 * в сутках + минута дня», то есть без совпадений при любом мыслимом числе закладок;
 * остаток по [ID_BATCH_LIMIT] удерживает результат в пределах `Int`.
 */
fun reminderNotificationId(batchId: Long, time: String): Int {
    val minute = minuteOfDay(time) ?: 0
    return ((batchId % ID_BATCH_LIMIT) * MINUTES_IN_DAY + minute).toInt()
}

private const val MINUTES_IN_DAY = 1_440L

/** Сколько закладок помещается в номер уведомления, не переполнив `Int`. */
private const val ID_BATCH_LIMIT = 1_000_000L

/** Минута суток для «ЧЧ:ММ»; `null` — время записано не так, как ожидалось. */
fun minuteOfDay(time: String): Int? {
    val parts = time.split(":")
    if (parts.size != 2) return null
    val hour = parts[0].trim().toIntOrNull() ?: return null
    val minute = parts[1].trim().toIntOrNull() ?: return null
    if (hour !in 0..23 || minute !in 0..59) return null
    return hour * 60 + minute
}

/**
 * Когда напоминание должно сработать в следующий раз — **строго после** [now].
 *
 * Здесь сидела ошибка, из-за которой уведомление приходило сразу же: время считалось
 * подстановкой часа и минуты в сегодняшний день, и для восьми утра, поставленных в два
 * часа дня, задержка выходила отрицательной. WorkManager отрицательную задержку
 * понимает как «немедленно», и человек получал напоминание в момент сохранения формы.
 * Прошедшее сегодня время переносится на завтра.
 *
 * Часовой пояс — параметр, а не константа, и берётся он заново при каждом счёте: «08:00»
 * — это восемь утра там, где человек сейчас, а не тот абсолютный момент, который был
 * восемью утра при постановке. Перелёт в другой пояс поэтому не сдвигает напоминание —
 * его пересчитывает и следующее срабатывание, и [TimeChangeReceiver].
 *
 * `null` — время нечитаемо; такое напоминание не ставится вовсе, чтобы не будить в
 * неизвестно какой час.
 */
fun nextReminderMillis(
    time: String,
    now: Long,
    zone: TimeZone = TimeZone.getDefault(),
): Long? {
    val minute = minuteOfDay(time) ?: return null
    val calendar = Calendar.getInstance(zone).apply {
        timeInMillis = now
        set(Calendar.HOUR_OF_DAY, minute / 60)
        set(Calendar.MINUTE, minute % 60)
        set(Calendar.SECOND, 0)
        set(Calendar.MILLISECOND, 0)
    }
    if (calendar.timeInMillis <= now) calendar.add(Calendar.DAY_OF_YEAR, 1)
    return calendar.timeInMillis
}

/**
 * Одно напоминание, готовое к постановке: чья закладка, во сколько и с каким текстом.
 *
 * Инкубатор здесь потому, что уведомление ведёт не в закладку саму по себе, а в неё
 * внутри её инкубатора: своего маршрута у шторки закладки нет. Раньше работа читала это
 * поле из базы при срабатывании; теперь оно приезжает вместе с планом, из которого
 * работа и так строится.
 */
data class ReminderJob(
    val batchId: Long,
    val incubatorId: Long,
    val title: String,
    val time: String,
    val note: String,
)

/**
 * Ближайший момент, когда приложению есть что показать, и всё, что на него приходится.
 *
 * Заданий обычно одно, но их может быть и несколько: две закладки, поставленные на
 * восемь утра, звенят вместе — у каждой своё уведомление со своим номером.
 */
data class FireMoment(val at: Long, val jobs: List<ReminderJob>)

/**
 * Ближайшее срабатывание по всему расписанию; `null` — напоминать нечего.
 *
 * Это и есть «диспетчер»: одна работа ставится на [FireMoment.at], а какие именно
 * закладки на него пришлись, считается здесь. Сортировка по времени внутри момента —
 * ради предсказуемого порядка уведомлений и ради теста.
 */
fun nextFire(
    jobs: List<ReminderJob>,
    now: Long,
    zone: TimeZone = TimeZone.getDefault(),
): FireMoment? {
    val moments = jobs.mapNotNull { job ->
        nextReminderMillis(job.time, now, zone)?.let { it to job }
    }
    val at = moments.minOfOrNull { it.first } ?: return null
    return FireMoment(at, moments.filter { it.first == at }.map { it.second })
}

/**
 * Что должно было прозвенеть в момент [at] — по расписанию, каким оно стало сейчас.
 *
 * Работа просыпается со своим моментом на руках, а список заданий строит заново по базе:
 * закладку могли завершить или удалить, время — убрать, текст — поправить. Считается от
 * `at - 1`, а не от текущего времени, именно потому, что проснуться работа могла сильно
 * позже: в Doze её откладывают на десятки минут, и «ближайшее к сейчас» было бы уже
 * завтрашним.
 */
fun jobsDueAt(
    jobs: List<ReminderJob>,
    at: Long,
    zone: TimeZone = TimeZone.getDefault(),
): List<ReminderJob> = jobs.filter { nextReminderMillis(it.time, at - 1, zone) == at }

/**
 * Закладка ждёт напоминаний — то есть идёт.
 *
 * Проверяется `arhive`, а не `status`: `BatchStatus` различает, чем закладка кончилась,
 * а напоминаниям важно только, кончилась ли она вообще.
 */
fun Batch.wantsReminders(): Boolean = arhive == "0"

/**
 * Что должно звенеть по нынешнему состоянию базы.
 *
 * Единственный ответ на этот вопрос в приложении: и постановка после правки формы, и
 * пересборка после импорта, и перепланирование внутри самой работы считают его одной и
 * той же функцией, поэтому разойтись им негде. Завершённые закладки сюда не попадают —
 * в этом и состоит требование «после завершения закладки уведомления не приходят»,
 * выраженное данными, а не последовательностью нажатий.
 */
fun plannedReminders(
    batches: List<Batch>,
    timesByBatch: Map<Long, List<Time>>,
): List<ReminderJob> = batches
    .filter { it.wantsReminders() }
    .flatMap { batch ->
        timesByBatch[batch.id].orEmpty()
            .filter { minuteOfDay(it.time) != null }
            // Два одинаковых времени внутри одной закладки — одно уведомление: будить
            // дважды в одну минуту незачем.
            .distinctBy { it.time }
            .map { ReminderJob(batch.id, batch.incubatorId, batch.title, it.time, it.note) }
    }
