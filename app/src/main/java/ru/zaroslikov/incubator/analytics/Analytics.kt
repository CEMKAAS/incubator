/**
 * Единственная дверь в AppMetrica из приложения.
 *
 * Раньше `AppMetrica.reportEvent` вызывался из десятка файлов литералом на месте, и
 * список событий существовал только в голове — то есть его не существовало. Воронку
 * строят по именам событий, и имя, которое нельзя перечислить, в воронку не поставить:
 * половина шагов «от установки до первого вывода» просто не отчитывалась (записанный
 * замер, записанное овоскопирование), а половина отчитывалась именами, по которым не
 * догадаться, что это за шаг (закладка — событием «Инкубатор», см. [Events]).
 *
 * Поэтому здесь два предмета, и оба обязательны:
 *
 * - **[Events]** — весь список имён в одном месте, с пометкой, какому шагу воронки имя
 *   принадлежит. Имена, доставшиеся от прежних экранов, сохранены дословно: ряд
 *   статистики за прошлые версии должен остаться сравнимым, и переименование его
 *   разорвало бы. Неудобство читается один раз, в комментарии, а не каждый месяц в
 *   отчёте.
 * - **профиль** ([reportProfile], [AnalyticsProfile]) — то, чем режутся когорты. Само
 *   удержание AppMetrica считает по сессиям и без нас, а вот вопрос «у кого удержание
 *   выше — у тех, кто завёл второй инкубатор, или у тех, кто выключил напоминания» без
 *   атрибутов профиля не задать.
 *
 * Событий с датами и деньгами здесь нет намеренно: приложение офлайновое, и всё, что
 * уходит наружу, — это обезличенные счётчики хозяйства плюс то, что человек сам вписал
 * в поля инкубатора (бренд, модель, название). Идентификатор профиля — случайный UUID
 * этой установки ([AppSettings.installationId]), не идентификатор устройства.
 */
object Analytics {

    /**
     * Ключ приложения в AppMetrica. Тот же, что стоял литералом в
     * `InventoryApplication`: другого нет, и второй ключ разорвал бы всю статистику.
     */
    private const val API_KEY = "cdc3cb4b-19cf-4469-aff8-5347d45faf69"

    /**
     * Включает AppMetrica. Вызывается из `InventoryApplication.onCreate`, то есть в
     * каждом процессе приложения — и в том, который WorkManager будит ради напоминания.
     * Так и надо: событие из работы иначе некуда было бы отправить.
     *
     * Что настроено помимо ключа:
     *
     * - **[AppMetricaConfig.Builder.withUserProfileID]** — без него атрибуты профиля
     *   отправлять некому: отчёт «Профили» и сегменты по атрибутам строятся вокруг
     *   этого идентификатора. Ставится при активации, а не вызовом
     *   `setUserProfileID` позже, чтобы у событий самого первого запуска профиль уже
     *   был — иначе первая сессия каждой установки выпадала бы из когорт.
     * - **`withLocationTracking(false)`** — приложение офлайновое и о месте не
     *   спрашивает; собирать координаты ради статистики незачем.
     * - **версия** — `BuildConfig.VERSION_NAME` вместо `versionName` из манифеста: там
     *   она та же, но здесь видно, что отчёт «по версиям» опирается на то же поле,
     *   которое показывает «О приложении».
     */
    fun activate(context: Context, settings: AppSettings) {
        val config = AppMetricaConfig.newConfigBuilder(API_KEY)
            .withAppVersion(BuildConfig.VERSION_NAME)
            .withUserProfileID(settings.installationId)
            .withLocationTracking(false)
            .build()
        AppMetrica.activate(context, config)
    }

    /** Событие без параметров. */
    fun report(event: String) {
        AppMetrica.reportEvent(event)
    }

    /**
     * Событие с параметрами.
     *
     * Пустые значения выбрасываются: `null` и пустая строка в отчёте — это ещё одна
     * строка разреза, по которой ничего не сгруппировать, а отличить «не заполнено» от
     * «параметра не было» в AppMetrica всё равно нельзя. Числа и `false` остаются:
     * ноль переворотов и выключенная автоматика — это ответы.
     *
     * Значением может быть вложенная карта — так собран отчёт об инкубаторе
     * ([incubationReport]): AppMetrica разворачивает JSON в дерево, и «Инкубатор →
     * Модель» читается как один разрез, а не как десяток параметров вперемешку с полями
     * закладки.
     *
     * **Отправляется JSON-строкой, а не картой, и это не вкусовщина.** У перегрузки
     * `reportEvent(String, Map)` поддерживаемые типы значений перечислены и вложенных
     * карт среди них нет — только строки, числа и `Boolean`; блок «Инкубатор» уехал бы
     * оттуда своим `toString()`, то есть строкой вида `{Бренд=Несушка, ...}`, по которой
     * в отчёте нельзя ни сгруппировать, ни отфильтровать. Вложенность документирована
     * ровно у JSON-перегрузки, ею и пользуемся. Для плоского события разницы нет:
     * AppMetrica и карту превращает в тот же JSON, только внутри себя.
     */
    fun report(event: String, params: Map<String, Any?>) {
        val filled = params.filterValues { it != null && it != "" }
        if (filled.isEmpty()) AppMetrica.reportEvent(event)
        else AppMetrica.reportEvent(event, jsonOf(filled).toString())
    }

    /**
     * Карта в JSON, вложенные карты — вложенными объектами.
     *
     * Ключи вложенной карты приводятся к строке: JSON других ключей не знает, а
     * собираются такие блоки в коде, где ключ всегда и так строка.
     */
    private fun jsonOf(params: Map<String, Any?>): JSONObject = JSONObject().apply {
        params.forEach { (key, value) ->
            val nested = value as? Map<*, *>
            put(key, if (nested != null) jsonOf(nested.mapKeys { it.key.toString() }) else value)
        }
    }

    /**
     * Атрибуты профиля — то, по чему режутся когорты и сегменты.
     *
     * Собирает их [AnalyticsProfile]: считать хозяйство по базе — не дело этого объекта,
     * он только отправляет.
     */
    fun reportProfile(profile: UserProfile) {
        AppMetrica.reportUserProfile(profile)
    }
}

