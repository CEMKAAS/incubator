package ru.zaroslikov.incubator.qr

/**
 * Что записано в QR-коде инкубатора: ссылка `incubator://measure/<id>`.
 *
 * Своя схема, а не `https://…`, и это не от лени. Ссылка на сайт открывала бы
 * приложение только через App Links — с доменом, файлом `assetlinks.json` на нём и
 * проверкой при установке; без подтверждённого домена Android 12+ открывает такую
 * ссылку браузером, и наклейка на инкубаторе вела бы на страницу, которой нет. Своя
 * схема ведёт в приложение всегда, когда оно установлено, — а на телефоне без него код
 * читается как текст, из которого хотя бы видно, чей он. Цена: камера не всякого
 * телефона предлагает открыть такую ссылку (штатная камера Pixel и Samsung — да), и
 * для остальных в приложении есть свой сканер.
 *
 * Внутри ссылки — только идентификатор инкубатора в базе. Не имя (его переименовывают,
 * а наклейка остаётся) и не идентификатор установки: база переезжает между телефонами
 * файлом (см. `DatabaseTransfer`) вместе с идентификаторами, и наклейки, напечатанные
 * до переезда, должны читаться после него. Код с чужого телефона указывает на
 * инкубатор, которого здесь нет, и сканер так и говорит.
 *
 * Разбор — чистая функция над строкой, без `android.net.Uri`: тот в JVM-тестах
 * заглушка, а формат ссылки должен быть пришпилен тестом ([QrLinkTest]).
 */
object QrLink {
    const val SCHEME = "incubator"
    const val HOST = "measure"

    private const val PREFIX = "$SCHEME://$HOST/"

    /** Текст, который кладётся в QR-код инкубатора с этим идентификатором. */
    fun encode(incubatorId: Long): String = PREFIX + incubatorId

    /**
     * Идентификатор инкубатора из текста QR-кода, либо `null`, если это не наша ссылка.
     *
     * Схема и хост — без учёта регистра (камеры и сканеры отдают текст как есть, но
     * `Uri` некоторых приложений нормализует схему в нижний регистр); пробелы по краям
     * и завершающий `/` терпимы. Всё остальное — чужой код, и он отклоняется целиком:
     * «почти наш» адрес с мусором после числа не должен вести в случайный инкубатор.
     */
    fun parse(text: String?): Long? {
        val s = text?.trim() ?: return null
        if (s.length <= PREFIX.length) return null
        if (!s.regionMatches(0, PREFIX, 0, PREFIX.length, ignoreCase = true)) return null
        val rest = s.substring(PREFIX.length).trimEnd('/')
        if (rest.isEmpty() || !rest.all { it in '0'..'9' }) return null
        val id = rest.toLongOrNull() ?: return null
        return if (id > 0) id else null
    }
}
