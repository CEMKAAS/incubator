package ru.zaroslikov.incubator.design.components

import androidx.activity.compose.LocalActivity
import androidx.compose.runtime.Composable
import androidx.compose.runtime.Stable
import androidx.compose.runtime.saveable.Saver
import androidx.compose.runtime.saveable.rememberSaveable

/**
 * Черновик формы, живущей в нижней шторке.
 *
 * Шторку сворачивают вниз пальцем — тем же движением, которым прокручивают её
 * содержимое, поэтому свернуть её случайно проще, чем закрыть нарочно. Свёрнутая
 * шторка ввод не теряет: открывшись снова, она показывает ровно то, что в ней
 * набрали. Крестик в заголовке — это отказ, и он ввод выбрасывает; уход с экрана
 * тоже.
 *
 * Сам ввод при этом лежит там, где и лежал, — во ViewModel формы, которая привязана
 * к экрану, а не к шторке, и переживает её закрытие. Здесь хранится только ответ на
 * вопрос «заполнять форму заново или оставить как есть»: [claim] возвращает `true`,
 * когда шторку открыли не тем же черновиком, каким свернули, и тогда её `load`
 * перечитывает всё с нуля.
 *
 * Один черновик приходится ровно на одну ViewModel, а не на одно место вызова:
 * форма закладки открывается и на создание, и на правку, но ViewModel у обеих одна,
 * и два черновика над одним состоянием обещали бы сохранить два разных ввода.
 */
@Stable
class SheetDraft private constructor(private var target: String?) {

    constructor() : this(null)

    /**
     * Отмечает, что шторку открыли с такими-то параметрами, и отвечает, нужно ли
     * заполнять форму заново.
     *
     * Ключ — всё, от чего зависит содержимое формы: идентификатор закладки, день
     * овоскопирования. Черновик закладки №7 не годится закладке №8, даже если шторку
     * не закрывали, а переоткрыли на соседней.
     */
    fun claim(vararg key: Any?): Boolean {
        val next = key.joinToString(SEPARATOR)
        if (target == next) return false
        target = next
        return true
    }

    /** Крестик, сохранение, уход с экрана — следующее открытие начнётся с чистой формы. */
    fun discard() {
        target = null
    }

    internal companion object {
        /** Разделитель ключа: в идентификаторах и днях его быть не может. */
        const val SEPARATOR = "\u0000"

        /**
         * Черновик переживает поворот экрана, но не смерть процесса.
         *
         * Ввод хранит ViewModel, а она переживает ровно смену конфигурации — поэтому
         * и метка сохраняется только вместе с ней. Записанная в `Bundle` без этой
         * оговорки, она пережила бы и убитый в фоне процесс, где ViewModel уже новая
         * и пустая: форма открылась бы пустой и такой бы и осталась, ведь `load` при
         * живой метке не зовут.
         */
        fun saver(keepsViewModel: () -> Boolean) = Saver<SheetDraft, String>(
            save = { draft -> draft.target.takeIf { keepsViewModel() } },
            restore = { SheetDraft(it) },
        )
    }
}

/**
 * Черновик, живущий до ухода с экрана.
 *
 * Вызывать его нужно в композиции **экрана**, а не самой шторки: композиция шторки
 * разбирается при её закрытии — черновик умер бы вместе с ней, и свёрнутая форма
 * теряла бы ввод. Композиция экрана разбирается при переходе на другой экран, и это
 * ровно тот случай, когда ввод и должен пропасть.
 *
 * У вложенных шторок — конструктора вида поверх формы закладки, овоскопирования
 * поверх закладки — «экран» это шторка-хозяйка: закрыли её, значит закрыли и то, что
 * стояло поверх.
 */
@Composable
fun rememberSheetDraft(): SheetDraft {
    val activity = LocalActivity.current
    return rememberSaveable(
        saver = SheetDraft.saver { activity?.isChangingConfigurations == true }
    ) { SheetDraft() }
}
