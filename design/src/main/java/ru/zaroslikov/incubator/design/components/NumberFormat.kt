package ru.zaroslikov.incubator.design.components

/**
 * **Любое число на экране печатается с разделителем разрядов**, и [formatCount] — то,
 * через что это делается: «1 200», «12 400 яиц», а не «1200» и «12400».
 *
 * Правило общее, а не денежное, и живёт оно поэтому здесь, а не рядом с деньгами:
 * четырёхзначное число без пробела читается как код, а не как количество. «1200» и
 * «12000» на плитке различаются одной цифрой в середине, и пересчитывать разряды
 * глазами приходится ровно там, где число и стоит, — в итоговой плитке, которую смотрят
 * мельком. Хозяйство на пару тысяч яиц — обычное дело, так что это не редкий случай.
 *
 * Пробел **неразрывный** (` `): обычный позволил бы переносу разорвать число между
 * разрядами, и «12 400» в узкой ячейке превратилось бы в «12» со строкой «400» под ним.
 *
 * Минус — типографский, а не дефис: рядом с моноширинными цифрами дефис теряется.
 *
 * Исключения — те числа, которые не количество: день инкубации («День 15/21»), номер
 * этапа овоскопирования, год, время, версия приложения, счётчик символов в поле имени.
 * Они не дорастают до четырёх знаков, а разделитель в них читался бы как ошибка.
 *
 * Через это проходят
 * `plural` (в `:app`, `ui/incubator/IncubatorTabParts.kt`) и
 * `formatMoney` (там же), то есть почти всё, чем в
 * приложении печатают количество; напрямую [formatCount] зовут там, где число стоит без
 * существительного, — в плитках и в заголовках.
 */
fun formatCount(value: Int): String {
    val sign = if (value < 0) "−" else ""
    return sign + groupDigits(kotlin.math.abs(value).toString())
}

/**
 * Разряды по три справа налево, через неразрывный пробел.
 *
 * Пробел записан escape'ом (`\u00A0`), а не символом: от обычного он в исходнике
 * неотличим на глаз, и достаточно одного редактора, нормализующего пробелы, чтобы
 * правило тихо перестало работать — а заметно это стало бы только в узкой ячейке
 * чужого телефона. `NumberFormatTest` проверяет именно этот символ.
 */
private fun groupDigits(digits: String): String =
    digits.reversed().chunked(3).joinToString("\u00A0").reversed()
