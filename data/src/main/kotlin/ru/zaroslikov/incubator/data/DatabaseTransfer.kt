package ru.zaroslikov.incubator.data

import android.content.Context
import android.database.sqlite.SQLiteDatabase
import android.database.sqlite.SQLiteException
import ru.zaroslikov.incubator.data.local.InventoryDatabase
import java.io.File
import java.io.InputStream
import java.io.OutputStream

/**
 * Выгрузка и загрузка базы целиком — «Управление данными» на экране настроек.
 *
 * Переносится сам файл SQLite, а не выгрузка в JSON. Причина простая: у базы восемь
 * таблиц, связанных внешними ключами с каскадами, и сериализатор пришлось бы держать в
 * согласии со схемой руками — на каждой миграции, вечно. Файл же по определению полон:
 * что бы в схему ни добавилось, копия это уносит и приносит обратно.
 *
 * Плата за это — файл нельзя открыть ничем, кроме этого же приложения, и он привязан к
 * версии схемы. Отсюда обе проверки при импорте: заголовок обязан быть заголовком
 * SQLite, а `user_version` — не больше текущей ([DATABASE_VERSION]). Файл постарше
 * принимается: Room прогонит по нему миграции при первом открытии, ровно как по базе
 * пользователя, который давно не обновлялся. Файл поновее не принимается никак —
 * миграций «вниз» в приложении нет и быть не может.
 *
 * Живёт здесь, а не в `:app`, по той же причине, что и [provideItemsRepository]: имя
 * файла базы, её версия и открытое соединение Room — детали модуля `:data`, и `:app`
 * их не видит.
 */

/** Имя файла базы. Оно же — ключ, по которому Room её открывает. */
const val DATABASE_NAME = "incubator_database"

/**
 * Версия схемы, которую понимает эта сборка. Совпадает с `@Database(version)`.
 *
 * Ручной дубликат: аннотацию отсюда не видно. Забыть поднять его вместе с версией базы
 * значит начать отвергать собственный экспорт этой же сборки — и узнается это у
 * пользователя, а не на сборке, поэтому пару стережёт `DatabaseVersionTest`.
 */
const val DATABASE_VERSION = 20

/**
 * Первые 16 байт всякого файла SQLite: строка «SQLite format 3» и **нулевой байт**.
 *
 * Именно нулевой, а не пробел. Разница в одном невидимом символе стоила рабочего
 * импорта: с пробелом на конце константа не совпадала ни с одним настоящим файлом,
 * и приложение отвергало всё подряд — включая собственный экспорт — со словами «это не
 * файл базы данных приложения». Поймать это чтением кода нельзя, только запуском.
 */
private val SQLITE_HEADER = "SQLite format 3\u0000".toByteArray(Charsets.US_ASCII)

/**
 * Таблица, которая есть в базе любой версии — от первой, где `Incubator` хранил ещё
 * закладки, до нынешней. По ней и отличаем свою базу от чужой.
 */
private const val PROBE_TABLE = "Incubator"

/** Чем закончилась попытка импорта. */
sealed interface ImportResult {
    /** База заменена. Приложение обязано перезапуститься: старое соединение закрыто. */
    data object Success : ImportResult

    /**
     * Файл не взят, и прежняя база не тронута — ни на диске, ни в памяти.
     * [reason] — готовый текст для человека.
     */
    data class Rejected(val reason: String) : ImportResult

    /**
     * Подмена сорвалась уже после закрытия базы; файл вернули на место, но соединение
     * с ним закрыто, и живой процесс работать дальше не может.
     *
     * Отдельный исход, а не [Rejected], потому что разговор с человеком тут другой.
     * «Не получилось, ваши данные на месте» — правда про диск и ложь про приложение:
     * репозиторий держит DAO уже закрытого экземпляра Room (`AppDataContainer` берёт
     * его один раз, лениво), и первый же запрос из любого живого экрана разобьётся о
     * закрытую базу. Человек увидит падение сразу после слов «данные на месте» и решит,
     * что импорт их всё-таки съел. Поэтому здесь, как и после успеха, остаётся ровно
     * одна кнопка — перезапустить.
     */
    data class RestoredNeedsRestart(val reason: String) : ImportResult
}

/**
 * Пишет копию базы в [out].
 *
 * Перед копированием обязателен `wal_checkpoint(FULL)`: Room открывает базу в режиме
 * WAL, и свежие записи лежат не в самом файле, а в соседнем `-wal`. Скопированный без
 * контрольной точки файл был бы базой на состояние «когда-то раньше» — без последних
 * замеров, а то и без последней закладки.
 */
fun exportDatabase(context: Context, out: OutputStream) {
    checkpoint(context)
    databaseFile(context).inputStream().use { it.copyTo(out) }
}

/**
 * Заменяет базу содержимым [input].
 *
 * Порядок шагов важен и выбран так, чтобы отказ не стоил пользователю данных: сначала
 * файл целиком принимается во временный, там же проверяется, и только заведомо годный
 * подменяет рабочий. Ошибка на любом шаге до подмены оставляет прежнюю базу нетронутой,
 * а `finally` уносит оба временных файла.
 *
 * **Подмена — единственный шаг, отказ на котором нечем было бы исправить**, поэтому у
 * неё есть откат. Копирование поверх файла начинается с его усечения: упади оно на
 * полпути — из-за кончившегося места, отозванного доступа к выбранному документу,
 * выдернутой флешки, — и на месте базы осталась бы половина чужой. Поэтому рабочий файл
 * сперва откладывается рядом целиком, и при любой ошибке возвращается на место.
 * Откладывается он уже после контрольной точки: копия базы, у которой свежие страницы
 * остались в `-wal`, откатом быть не может.
 *
 * Вместе с базой удаляются `-wal` и `-shm`. Оставить их нельзя: они относятся к прежнему
 * файлу, и SQLite, увидев журнал от другой базы, либо накатит на неё чужие страницы,
 * либо откажется открывать.
 */
fun importDatabase(context: Context, input: InputStream): ImportResult {
    val incoming = File(context.cacheDir, "$DATABASE_NAME.import")
    val target = databaseFile(context)
    // Кандидат лежит рядом с рабочей базой, а не в кэше, по двум причинам: его открывает
    // Room (значит, каталог должен быть постоянным и доступным на запись), и подменять
    // им рабочий файл нужно переименованием, а оно атомарно только внутри одной ФС.
    val candidate = File(target.parentFile, "$DATABASE_NAME.candidate")
    val backup = File(target.parentFile, "$DATABASE_NAME.backup")

    // Закрыта ли уже рабочая база. От этого зависит, чем кончится сорвавшаяся подмена:
    // до закрытия отказ ничего не стоит, после — процесс придётся перезапустить.
    var closed = false

    try {
        incoming.outputStream().use { input.copyTo(it) }

        val problem = inspect(incoming)
        if (problem != null) return ImportResult.Rejected(problem)

        // Room проверяет кандидата **до** того, как рабочая база хотя бы закрыта: пока
        // мы не тронули ни файла, отказ ничего не стоит.
        candidate.parentFile?.mkdirs()
        incoming.copyTo(candidate, overwrite = true)
        val roomProblem = openable(context, candidate)
        if (roomProblem != null) return ImportResult.Rejected(roomProblem)

        // Весь перенос — под монитором синглтона Room: пока он держится, `getDatabase`
        // не может открыть рабочий файл заново, и подменять его безопасно.
        InventoryDatabase.exclusively {
            // Сгоняем WAL в файл до закрытия — иначе отложенная копия окажется неполной.
            if (target.exists()) checkpoint(context)
            InventoryDatabase.closeAndForget()
            closed = true

            if (target.exists()) target.copyTo(backup, overwrite = true)
            File(target.path + "-wal").delete()
            File(target.path + "-shm").delete()

            // Переименование, а не копирование: `copyTo` начинается с усечения цели, и
            // убитый посреди него процесс оставил бы на месте базы обрубок. `rename(2)`
            // внутри одной ФС подменяет файл целиком и неделимо — момента, в который базы
            // нет, не существует вовсе, чем бы процесс ни прервали.
            if (!candidate.renameTo(target)) {
                // Единственная причина, по которой это может не сработать, — цель и
                // кандидат вдруг оказались на разных ФС. Тогда честно копируем, и тогда же
                // нужен откат.
                try {
                    candidate.copyTo(target, overwrite = true)
                } catch (e: Exception) {
                    if (backup.exists()) backup.copyTo(target, overwrite = true)
                    throw e
                }
            }
        }

        return ImportResult.Success
    } catch (e: Exception) {
        val detail = e.message ?: "неизвестная ошибка"
        // Откат уже случился выше; здесь решается только, что сказать человеку.
        return if (closed) {
            ImportResult.RestoredNeedsRestart(
                "Не удалось заменить базу: $detail. Ваши данные на месте, но приложение " +
                    "нужно перезапустить."
            )
        } else {
            ImportResult.Rejected("Не удалось прочитать файл: $detail. Ваши данные на месте.")
        }
    } finally {
        incoming.delete()
        backup.delete()
        // Кандидат и его журналы: `renameTo` уносит сам файл, но не спутников, которые
        // мог оставить Room при проверке.
        candidate.delete()
        File(candidate.path + "-wal").delete()
        File(candidate.path + "-shm").delete()
        File(incoming.path + "-wal").delete()
        File(incoming.path + "-shm").delete()
        // Room кладёт рядом с кэшем файл блокировки по имени базы — свой у кандидата.
        // Он пустой и лежит в кэше, но остаётся после каждой попытки импорта, а
        // прибрать за собой дешевле, чем однажды объяснять, откуда он взялся.
        File(context.cacheDir, "$DATABASE_NAME.candidate.lck").delete()
    }
}

/**
 * Открывает кандидата настоящим Room и возвращает причину отказа или `null`.
 *
 * **Это единственная проверка, которая действительно отвечает на нужный вопрос.**
 * Заголовок, наличие таблицы `Incubator` и `user_version` из [inspect] — приметы, а не
 * доказательство: любая база с таблицей такого имени их проходит, а открывать её потом
 * будет Room, который сверяет identity hash схемы из `room_master_table` и падает с
 * «Room cannot verify the data integrity», если схема чужая. Файл постарше вместо этого
 * поедет по миграциям и разобьётся на первом же `ALTER TABLE`.
 *
 * Чем это грозило, стоит держать в голове: подменённая база уничтожена, резервная копия
 * удалена, процесс убит — и приложение падает при каждом запуске, потому что открыть
 * базу оно больше не может. Выбраться можно только «Очистить данные», то есть потеряв
 * всё. Поэтому кандидат открывается заранее, отдельным экземпляром Room по своему имени
 * файла, с теми же миграциями, и у него запрашивается строка — открытие Room ленивое,
 * без запроса схема не проверяется.
 *
 * Побочная польза: если файл был старой версии, миграции уже прогнались **по кандидату**,
 * и на место рабочей базы встаёт файл нужной схемы.
 */
private fun openable(context: Context, candidate: File): String? {
    var db: InventoryDatabase? = null
    return try {
        db = InventoryDatabase.buildFor(context, candidate.name)
        // Любой запрос: он и заставляет Room открыть базу и сверить схему.
        db.openHelper.writableDatabase.query("SELECT count(*) FROM Incubator").use {
            it.moveToFirst()
        }
        // Сгоняем WAL кандидата в его файл — переименуем мы только сам файл.
        db.openHelper.writableDatabase.query("PRAGMA wal_checkpoint(FULL)").use {
            it.moveToFirst()
        }
        null
    } catch (e: Exception) {
        // Текст исключения сюда не попадает намеренно. Room на несовпадении схемы
        // печатает обе таблицы целиком, поле за полем, — это сотни строк, которые в
        // диалоге выглядят как поломка приложения, а не как ответ на вопрос «почему не
        // взяли мой файл». Человеку нужно знать, что файл чужой; подробности нужны
        // разработчику, и он найдёт их в логе.
        "Файл не открывается этой версией приложения — похоже, он от другой " +
            "программы или собран более новой версией."
    } finally {
        db?.close()
    }
}

/**
 * Проверяет принятый файл. Возвращает причину отказа или `null`, если файл годен.
 *
 * Три проверки по возрастанию цены: длина и заголовок читаются из первых байтов, а
 * открывать файл базой имеет смысл, только когда он на неё хотя бы похож — иначе
 * SQLite бросит исключение там, где хватило бы взгляда на шестнадцать байт.
 */
private fun inspect(file: File): String? {
    if (file.length() < SQLITE_HEADER.size) return "Файл пуст или повреждён."

    val header = ByteArray(SQLITE_HEADER.size)
    file.inputStream().use { it.read(header) }
    if (!header.contentEquals(SQLITE_HEADER)) {
        return "Это не файл базы данных приложения."
    }

    var db: SQLiteDatabase? = null
    try {
        db = SQLiteDatabase.openDatabase(file.path, null, SQLiteDatabase.OPEN_READONLY)

        if (!hasTable(db, PROBE_TABLE)) {
            return "В файле нет таблиц приложения — похоже, база от другой программы."
        }

        val version = db.version
        return when {
            version <= 0 -> "У файла не проставлена версия схемы — открыть его нечем."
            version > DATABASE_VERSION ->
                "Файл сохранён более новой версией приложения (схема $version, " +
                    "здесь $DATABASE_VERSION). Обновите приложение."

            else -> null
        }
    } catch (e: SQLiteException) {
        return "Файл повреждён и не открывается как база данных."
    } finally {
        db?.close()
    }
}

private fun hasTable(db: SQLiteDatabase, name: String): Boolean =
    db.rawQuery(
        "SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?",
        arrayOf(name)
    ).use { it.moveToFirst() }

/**
 * Сгоняет содержимое WAL в сам файл базы.
 *
 * Открывает базу через Room намеренно: контрольная точка нужна на том самом соединении,
 * которое в неё пишет. Второе соединение поверх файла увидело бы свой WAL, а не чужой.
 */
private fun checkpoint(context: Context) {
    val helper = InventoryDatabase.getDatabase(context).openHelper
    val db = helper.writableDatabase

    // Итог контрольной точки обязателен к проверке. `wal_checkpoint` возвращает три
    // числа, и первое из них — признак неудачи: единица означает, что кто-то читал базу
    // и журнал слить не удалось. Читатели у приложения есть всегда — каждый список на
    // экране держит свой Flow, — так что случай не гипотетический. Не посмотрев на это
    // число, экспорт молча отдал бы копию без последних замеров, а узнал бы об этом
    // человек только когда стал бы из неё восстанавливаться.
    val busy = db.query("PRAGMA wal_checkpoint(TRUNCATE)").use {
        if (it.moveToFirst()) it.getInt(0) else 0
    }
    if (busy == 0) return

    // Одна повторная попытка: занятость — состояние мгновения, а читатели приложения
    // отпускают базу сразу после запроса. Если и она не прошла — лучше отказать, чем
    // выдать неполную копию за полную.
    val retry = db.query("PRAGMA wal_checkpoint(TRUNCATE)").use {
        if (it.moveToFirst()) it.getInt(0) else 0
    }
    check(retry == 0) {
        "база сейчас занята, копия вышла бы неполной — попробуйте ещё раз"
    }
}

private fun databaseFile(context: Context): File = context.getDatabasePath(DATABASE_NAME)

/**
 * Контрольная точка перед резервной копией Android.
 *
 * Автобэкап копирует файл базы как есть, а Room держит её в режиме WAL: свежие записи
 * лежат в соседнем `-wal`, который в копию не идёт (он исключён правилами — журнал от
 * чужой базы либо накатит на восстановленную посторонние страницы, либо не даст ей
 * открыться). Без этого вызова в облако уходила бы база на момент последней контрольной
 * точки, то есть без последних замеров, а то и без последней закладки. Ровно та же
 * причина, по какой её делает [exportDatabase].
 *
 * В отличие от экспорта, здесь неудача не повод отказываться: экспорт обещает человеку
 * полную копию и вправе сказать «попробуйте ещё раз», а бэкап случается сам, без него,
 * и уронить его исключением значило бы не иметь копии вовсе. Занятая база — состояние
 * мгновения, следующий бэкап застанет её свободной.
 *
 * @return удалось ли слить журнал; `false` — копия будет чуть старше.
 */
fun checkpointForBackup(context: Context): Boolean {
    if (!databaseFile(context).exists()) return true
    return runCatching { checkpoint(context) }.isSuccess
}

/**
 * Удаляет базу целиком — «Удалить все данные» на экране настроек.
 *
 * Удаляется **файл**, а не строки таблиц. `DELETE FROM` по восьми таблицам пришлось бы
 * держать в согласии со схемой руками, на каждой миграции, — ровно та работа, которой
 * избегает перенос файлом; забытая таблица оставила бы после «удаления всего» живые
 * строки. Файл же не знает о схеме ничего: его нет — значит, нет ничего. Room откроет
 * базу заново при первом обращении и создаст её пустой, нужной версии, без миграций.
 *
 * Всё остальное здесь — то же, что и у подмены при импорте, и по тем же причинам:
 * работа идёт под монитором синглтона, чтобы никто не открыл файл в промежутке между
 * закрытием и удалением, а `-wal` и `-shm` уходят вместе с базой — журнал от удалённого
 * файла либо накатится на новую пустую базу чужими страницами, либо не даст её открыть.
 *
 * **После вызова процесс обязан перезапуститься.** Соединение закрыто, а живые
 * ViewModel и их потоки говорят о данных, которых больше нет, — ровно как после
 * импорта. Перезапуск делает `DataTransferController`.
 */
fun wipeDatabase(context: Context) {
    val target = databaseFile(context)
    InventoryDatabase.exclusively {
        InventoryDatabase.closeAndForget()
        target.delete()
        File(target.path + "-wal").delete()
        File(target.path + "-shm").delete()
    }
}
